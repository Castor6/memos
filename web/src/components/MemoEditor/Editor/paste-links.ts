import { Fragment, type Node as ProseMirrorNode, Slice } from "@tiptap/pm/model";
import { isHttpUrl } from "@/utils/http-url";

const LINK_PREFIX = /^(?:https?:\/\/|mailto:)/i;

/**
 * Whether a link only exists because the source app auto-linked a bare `www.` host or email
 * (its text is the href minus the protocol). Links with their own label, and http(s) text, are kept.
 */
export function isAutoGeneratedLink(text: string, href: unknown): boolean {
  const label = text.trim();
  if (!label || typeof href !== "string" || isHttpUrl(label) || !/[.@]/.test(label)) return false;
  const target = href.trim().replace(LINK_PREFIX, "").replace(/\/+$/, "");
  return target.toLowerCase().startsWith(label.toLowerCase());
}

const stripFragment = (fragment: Fragment): Fragment => {
  const children: ProseMirrorNode[] = [];
  fragment.forEach((node) => {
    if (node.isText) {
      const link = node.marks.find((mark) => mark.type.name === "link");
      children.push(link && isAutoGeneratedLink(node.text ?? "", link.attrs.href) ? node.mark(link.removeFromSet(node.marks)) : node);
    } else {
      children.push(node.copy(stripFragment(node.content)));
    }
  });
  return Fragment.fromArray(children);
};

/** Drops auto-generated `www.`/email links from pasted rich content, keeping the pasted text as-is. */
export const stripAutoGeneratedLinks = (slice: Slice): Slice => new Slice(stripFragment(slice.content), slice.openStart, slice.openEnd);
